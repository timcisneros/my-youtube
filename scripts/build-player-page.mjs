import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { brotliCompressSync, constants as zlibConstants, gzipSync } from 'node:zlib';
import { transformSync } from 'esbuild';

const root = path.resolve(import.meta.dirname, '..');
const sourcePath = path.join(root, 'views', 'player.ejs');
const outputPath = path.join(root, 'public', 'player-page.js');
const minOutputPath = path.join(root, 'public', 'player-page.min.js');
const nativeSourcePath = path.join(root, 'public', 'native-player-engine.js');
const nativeMinOutputPath = path.join(root, 'public', 'native-player-engine.min.js');
const telemetryOutputPath = path.join(root, 'public', 'player-telemetry.js');
const telemetryMinOutputPath = path.join(root, 'public', 'player-telemetry.min.js');
const appPath = path.join(root, 'public', 'app.js');
const idbHelpersPath = path.join(root, 'public', 'idb-helpers.js');
const stylePath = path.join(root, 'public', 'style.css');
const serviceWorkerPath = path.join(root, 'public', 'sw.js');

function minify(source, sourcefile) {
  return transformSync(source, {
    loader: 'js',
    minify: true,
    target: 'es2020',
    legalComments: 'none',
    sourcefile,
  }).code;
}

function expandIncludes(source) {
  return source.replace(/<%-\s*include\('player\/([^']+)'\)\s*%>/g, (_match, name) => {
    return fs.readFileSync(path.join(root, 'views', 'player', `${name}.ejs`), 'utf8');
  });
}

const source = fs.readFileSync(sourcePath, 'utf8');
const startMarker = "    <script>\n<%- include('player/linkify') %>";
const start = source.indexOf(startMarker);
const end = source.lastIndexOf('    </script>');
if (start === -1 || end === -1 || end <= start) throw new Error('Could not locate player runtime script');

let runtime = source.slice(start + '    <script>\n'.length, end);
runtime = expandIncludes(runtime);

const replacements = new Map([
  ["<%- JSON.stringify(typeof playerDrmServers !== 'undefined' ? playerDrmServers : {}) %>", 'bootstrap.playerDrmServers || {}'],
  ["<%= typeof downloadedHeight !== 'undefined' ? downloadedHeight : 0 %>", 'Number(bootstrap.downloadedHeight) || 0'],
  ["<%= video.liveStatus === 'is_live' ? 'true' : 'false' %>", "bootstrap.liveStatus === 'is_live'"],
  ["<%- JSON.stringify(typeof playlist !== 'undefined' && playlist ? playlist.prevUrl : '') %>", "bootstrap.playlistPrevUrl || ''"],
  ["<%- JSON.stringify(typeof playlist !== 'undefined' && playlist ? playlist.nextUrl : '') %>", "bootstrap.playlistNextUrl || ''"],
  ["<%- JSON.stringify(typeof requestedPlaylistId !== 'undefined' ? requestedPlaylistId : '') %>", "bootstrap.requestedPlaylistId || ''"],
  ["<%= typeof requestedPlaylistIndex !== 'undefined' ? requestedPlaylistIndex : 0 %>", 'Number(bootstrap.requestedPlaylistIndex) || 0'],
  ["<%= (typeof video !== 'undefined' && video.duration) || 0 %>", 'Number(bootstrap.duration) || 0'],
  ["<%= startTime || 0 %>", 'Number(bootstrap.startTime) || 0'],
  ["<%= typeof savedPosition !== 'undefined' ? savedPosition : 0 %>", 'Number(bootstrap.savedPosition) || 0'],
]);
for (const [from, to] of replacements) runtime = runtime.replaceAll(from, to);

runtime = runtime.replace(
  /<% if \(typeof inlineVia[^%]+%>finalVia = '<%= inlineVia %>';<% } %>/,
  'if (bootstrap.inlineVia) finalVia = bootstrap.inlineVia;',
);
runtime = runtime.replace(/<%= video\.title.*?%>/g, "' + (bootstrap.title || videoId) + '");
runtime = runtime.replace(/<%= \(video\.channelTitle.*?%>/g, "' + (bootstrap.channelTitle || '') + '");
runtime = runtime.replaceAll('<%= streamToken %>', "' + (bootstrap.streamToken || '') + '");
runtime = runtime.replaceAll('<%= video.videoId %>', "' + videoId + '");

const remainingEjs = runtime.match(/<%[\s\S]*?%>/g);
if (remainingEjs) throw new Error(`Unconverted player EJS: ${remainingEjs.join(', ')}`);

const output = `// Generated by scripts/build-player-page.mjs from views/player.ejs and player partials.\n` +
`(function () {\n` +
`  'use strict';\n` +
`  var bootstrap = window.__playerBootstrap || {};\n` +
`  var videoId = String(bootstrap.videoId || '');\n` +
`  window.__playerPageRuntimeLoaded = true;\n` +
runtime +
`\n})();\n`;
const minOutput = minify(output, 'player-page.js');
const nativeSource = fs.readFileSync(nativeSourcePath, 'utf8');
const telemetryStartMarker = '  function PlayerTelemetry(engine) {';
const telemetryEndMarker = '  function PlayerAdapter(engine) {';
const telemetryStart = nativeSource.indexOf(telemetryStartMarker);
const telemetryEnd = nativeSource.indexOf(telemetryEndMarker, telemetryStart);
if (telemetryStart === -1 || telemetryEnd === -1) throw new Error('Could not locate player telemetry feature block');
const telemetryBlock = nativeSource.slice(telemetryStart, telemetryEnd);
const telemetryOutput = `// Generated optional telemetry feature chunk from native-player-engine.js.\n` +
`(function () {\n` +
`  'use strict';\n` +
`  function isOnline() {\n` +
`    return !('navigator' in window) || !('onLine' in navigator) || navigator.onLine;\n` +
`  }\n` +
`  function merge(target, src) {\n` +
`    for (var key in src) {\n` +
`      if (!Object.prototype.hasOwnProperty.call(src, key)) continue;\n` +
`      if (src[key] && typeof src[key] === 'object' && !Array.isArray(src[key])) {\n` +
`        if (!target[key]) target[key] = {};\n` +
`        merge(target[key], src[key]);\n` +
`      } else {\n` +
`        target[key] = src[key];\n` +
`      }\n` +
`    }\n` +
`    return target;\n` +
`  }\n` +
telemetryBlock +
`  window.PlayerTelemetry = PlayerTelemetry;\n` +
`})();\n`;
const telemetryMinOutput = minify(telemetryOutput, 'player-telemetry.js');
const telemetryFallback = `  function PlayerTelemetry(engine) {\n` +
`    this.engine = engine;\n` +
`    this.events = [];\n` +
`    this.destroyed = false;\n` +
`  }\n` +
`  PlayerTelemetry.prototype.attach = function () {};\n` +
`  PlayerTelemetry.prototype.record = function () {};\n` +
`  PlayerTelemetry.prototype.scheduleFlush = function () {};\n` +
`  PlayerTelemetry.prototype.flush = function () {};\n` +
`  PlayerTelemetry.prototype.destroy = function () { this.destroyed = true; this.events = []; };\n\n`;
const nativeCoreSource = nativeSource.slice(0, telemetryStart) + telemetryFallback + nativeSource.slice(telemetryEnd);
const nativeMinOutput = minify(nativeCoreSource, 'native-player-engine.js');
const generatedAssets = new Map([
  [outputPath, Buffer.from(output)],
  [minOutputPath, Buffer.from(minOutput)],
  [nativeSourcePath, Buffer.from(nativeSource)],
  [nativeMinOutputPath, Buffer.from(nativeMinOutput)],
  [telemetryOutputPath, Buffer.from(telemetryOutput)],
  [telemetryMinOutputPath, Buffer.from(telemetryMinOutput)],
  [appPath, fs.readFileSync(appPath)],
  [idbHelpersPath, fs.readFileSync(idbHelpersPath)],
  [stylePath, fs.readFileSync(stylePath)],
]);

function versionedAssetUrl(assetPath, contents) {
  const version = createHash('sha256').update(contents).digest('hex').slice(0, 16);
  return `/${path.basename(assetPath)}?v=${version}`;
}

const assetUrlEntries = {
  idbHelpers: versionedAssetUrl(idbHelpersPath, generatedAssets.get(idbHelpersPath)),
  app: versionedAssetUrl(appPath, generatedAssets.get(appPath)),
  style: versionedAssetUrl(stylePath, generatedAssets.get(stylePath)),
  nativePlayer: versionedAssetUrl(nativeMinOutputPath, generatedAssets.get(nativeMinOutputPath)),
  playerTelemetry: versionedAssetUrl(telemetryMinOutputPath, generatedAssets.get(telemetryMinOutputPath)),
  playerPage: versionedAssetUrl(minOutputPath, generatedAssets.get(minOutputPath)),
};
const assetRevision = createHash('sha256')
  .update(Object.values(assetUrlEntries).join('\n'))
  .digest('hex')
  .slice(0, 16);
const runtimeAssetUrls = { ...assetUrlEntries, revision: assetRevision };
const serviceWorkerSource = fs.readFileSync(serviceWorkerPath, 'utf8');
const serviceWorkerOutput = serviceWorkerSource.replace(
  /\/\/ RUNTIME_ASSET_URLS_START\n[\s\S]*?\n\/\/ RUNTIME_ASSET_URLS_END/,
  `// RUNTIME_ASSET_URLS_START\nvar RUNTIME_ASSET_URLS = ${JSON.stringify(runtimeAssetUrls)};\n// RUNTIME_ASSET_URLS_END`,
);
if (serviceWorkerOutput === serviceWorkerSource && serviceWorkerSource.includes('"revision":"build"')) {
  throw new Error('Could not update service worker runtime asset URLs');
}

function compressedVersions(buffer) {
  return {
    br: brotliCompressSync(buffer, {
      params: {
        [zlibConstants.BROTLI_PARAM_QUALITY]: 11,
        [zlibConstants.BROTLI_PARAM_MODE]: zlibConstants.BROTLI_MODE_TEXT,
      },
    }),
    gz: gzipSync(buffer, { level: 9 }),
  };
}

const compressedAssets = new Map();
for (const [assetPath, contents] of generatedAssets) {
  const compressed = compressedVersions(contents);
  compressedAssets.set(`${assetPath}.br`, compressed.br);
  compressedAssets.set(`${assetPath}.gz`, compressed.gz);
}

if (process.argv.includes('--check')) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
  const currentMin = fs.existsSync(minOutputPath) ? fs.readFileSync(minOutputPath, 'utf8') : '';
  const currentNativeMin = fs.existsSync(nativeMinOutputPath) ? fs.readFileSync(nativeMinOutputPath, 'utf8') : '';
  const currentTelemetry = fs.existsSync(telemetryOutputPath) ? fs.readFileSync(telemetryOutputPath, 'utf8') : '';
  const currentTelemetryMin = fs.existsSync(telemetryMinOutputPath) ? fs.readFileSync(telemetryMinOutputPath, 'utf8') : '';
  const currentServiceWorker = fs.existsSync(serviceWorkerPath) ? fs.readFileSync(serviceWorkerPath, 'utf8') : '';
  const compressedAssetsCurrent = [...compressedAssets].every(([assetPath, contents]) => (
    fs.existsSync(assetPath) && fs.readFileSync(assetPath).equals(contents)
  ));
  if (current !== output || currentMin !== minOutput || currentNativeMin !== nativeMinOutput
    || currentTelemetry !== telemetryOutput || currentTelemetryMin !== telemetryMinOutput
    || currentServiceWorker !== serviceWorkerOutput || !compressedAssetsCurrent) {
    console.error('Generated player assets are stale; run npm run build:player-page');
    process.exitCode = 1;
  }
} else {
  fs.writeFileSync(outputPath, output);
  fs.writeFileSync(minOutputPath, minOutput);
  fs.writeFileSync(nativeMinOutputPath, nativeMinOutput);
  fs.writeFileSync(telemetryOutputPath, telemetryOutput);
  fs.writeFileSync(telemetryMinOutputPath, telemetryMinOutput);
  fs.writeFileSync(serviceWorkerPath, serviceWorkerOutput);
  for (const [assetPath, contents] of compressedAssets) fs.writeFileSync(assetPath, contents);
}
